#!/usr/bin/env python3
"""Generates src/attn_dummy_weights.h - const (flash-resident) dummy weights for
STFT_DEBUG_ATTENTION_TEST, replacing the runtime-filled external-SRAM weights used in the
earlier version of this probe. Values match attnFillDummyInt8()'s exact formula/seeds
bit-for-bit (see main.c) - only the storage location changes, isolating that as the sole
variable versus the previous external-SRAM measurement, same rigor as the K/V-in-internal-RAM
test that preceded this one.

Regenerate after changing ATTN_EMBED_DIM (E below) or ATTN_N_HEADS (H below) in main.c:
    python3 scripts/gen_attn_dummy_weights.py > src/attn_dummy_weights.h
"""

E = 32  # must match ATTN_EMBED_DIM in main.c
H = 4   # must match ATTN_N_HEADS in main.c
D = E // H
F = 4 * E  # must match ATTN_FFN_DIM in main.c


def fill(count, seed):
    return [((i + seed) * 7 + 3) % 21 - 10 for i in range(count)]


def emit(name, values, per_line=20):
    print(f"static const int8_t {name}[{len(values)}] = {{")
    for i in range(0, len(values), per_line):
        print("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    print("};\n")


def main():
    print("/* Generated by scripts/gen_attn_dummy_weights.py - see main.c's own comment on")
    print("   attnQkvWeightConst etc. for why these exist (const/flash instead of runtime-")
    print("   filled external SRAM). Do not hand-edit - regenerate instead (see this file's")
    print("   own docstring). */")
    print()
    emit("attnQkvWeightConst", fill(3 * E * E, 0))
    emit("attnOutProjWeightConst", fill(E * E, 11))
    emit("attnLinear1WeightConst", fill(F * E, 23))
    emit("attnLinear2WeightConst", fill(E * F, 37))
    print(f"static const int32_t attnQkvBiasConst[{3 * E}] = {{0}};")
    print(f"static const int32_t attnOutProjBiasConst[{E}] = {{0}};")
    print(f"static const int32_t attnLinear1BiasConst[{F}] = {{0}};")
    print(f"static const int32_t attnLinear2BiasConst[{E}] = {{0}};")


if __name__ == "__main__":
    main()
